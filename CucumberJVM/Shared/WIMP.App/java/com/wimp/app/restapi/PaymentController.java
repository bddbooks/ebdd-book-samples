package com.wimp.app.restapi;

import com.wimp.app.models.Payment;
import com.wimp.app.models.ServiceResult;
import com.wimp.app.services.PaymentService;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.server.ResponseStatusException;

@RestController
@RequestMapping("/api/payment")
@Transactional
public class PaymentController {
    private final PaymentService paymentService;

    public PaymentController(PaymentService paymentService) {
        this.paymentService = paymentService;
    }

    @PostMapping("/authorize")
    public ResponseEntity<Payment> authorizePayment(@RequestParam int orderNo) {
        ServiceResult<Payment> result = paymentService.authorizePaymentFor(orderNo);
        if (!result.successful()) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, result.errorMessage());
        }

        return ResponseEntity.ok(result.value());
    }
}
